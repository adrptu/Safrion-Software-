# -*- coding: utf-8 -*-
"""Jornada 1: pré-carga → MB-01 fila → rodapé leva a MB-05 → confirmar → MB-03 iniciar → sem sinal → fechar 60 ha → sinal volta."""
import sys, os, time; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ver_appv_lib import V, precarga
a = V(); OS = 'OS-0430'
try:
    rid = precarga(a)
    a.abrir('MB-01'); m = a.main()
    ids = a.J("[...document.querySelectorAll('main b')].map(b=>b.innerText).filter(t=>/^OS-/.test(t))")
    print('   fila:', ids, '| hdr:', a.hdr(), '| foot:', a.foot())
    a.ok(ids[:3] == ['OS-0421', 'OS-0424', 'OS-0430'], 'MB-01 ordem de janela: ' + str(ids))
    a.ok('Entregue por Rui · ' + rid in m and a.foot() == f'Confirmar recebimento · {OS}', 'MB-01 card entregue + rodapé confirmar: ' + a.foot())
    print('   corte', a.corte())
    a.shot('ver_appv2_mb01_entregue.png')
    r = a.clk(f'Confirmar recebimento · {OS}', wait=1.8); print('   clk', r, a.path())
    a.ok(a.path().endswith('MB-05.dc.html'), 'rodapé MB-01 leva a MB-05: ' + a.path())
    a.abrir('MB-05'); m = a.main(); print(m[:1500]); print('   hdr', a.hdr(), '| foot', a.foot(), '| corte', a.corte())
    a.shot('ver_appv2_mb05_entregue.png')
    r = a.clk('Confirmar recebimento', wait=.6); t = a.toast(); print('   clk', r, '| toast', t)
    a.ok(a.cen(f"c.reqs['{rid}'].itens.every(i=>i.confirmado)"), 'MB-05 confirmar grava')
    print('   depois:', a.main()[:900], '| hdr', a.hdr(), '| foot', a.foot())
    a.abrir('MB-03'); print('   MB-03 foot', a.foot(), a.J("[...document.querySelectorAll('main button')].map(b=>b.title).join(' | ')"))
    a.clk_sel(f'button[title="Iniciar turno na {OS}"]', wait=.6)
    print('   toast', a.toast(), '| hdr', a.hdr(), '| foot', a.foot())
    a.ok(a.cen(f"c.ordens['{OS}'].etapa") == 'Em execução' and a.foot() == 'Fechar turno', 'MB-03 iniciar: Em execução e rodapé Fechar turno')
    a.clk('Sem sinal'); print('   sinal', a.cen('c.app.online'), a.J("document.querySelector('[aria-live]').innerText"), '| toast', a.toast())
    a.setv('#ft_ha', '60'); a.setv('#ft_h', '5')
    vals = a.J("[0,1,2].map(i=>{const e=document.querySelector('#ft_c'+i); return e?e.value:null;})"); print('   consumo pré:', vals)
    a.ok(vals == ['120', '60', '30'], 'consumo pré-calculado dose × ha: ' + str(vals))
    a.shot('ver_appv2_mb03_form.png')
    a.clk('Fechar turno', wait=.6); t = a.toast(); print('   toast', t)
    print('   estado: fila', a.cen('c.app.fila'), 'real', a.cen(f"c.ordens['{OS}'].realizado"), 'saldo', a.cen(f"c.ordens['{OS}'].saldo"), 'etapa', a.cen(f"c.ordens['{OS}'].etapa"),
          'cust', a.cen(f"c.reqs['{rid}'].itens.map(i=>i.prod+':'+i.custodia+'/'+i.consumido)"))
    m = a.main(); print(m[:1400]); print('   hdr', a.hdr(), '| foot', a.foot())
    a.ok(a.cen('c.app.fila.length') == 1 and a.cen(f"c.ordens['{OS}'].realizado") == 0 and '1 registro aguardando sinal' in m, 'fechar sem sinal: fila 1, realizado 0')
    a.shot('ver_appv2_mb03_fechado_off.png')
    a.abrir('MB-01'); print('   MB-01 off:', a.hdr(), '|', [l for l in a.main().split('\n') if 'aparelho' in l or 'Realizado' in l], '| foot', a.foot())
    a.clk('Com sinal', wait=.6); t = a.toast(); print('   toast', t)
    a.ok(a.cen(f"c.ordens['{OS}'].realizado") == 60 and a.cen('c.app.fila.length') == 0 and 'REC-7742' in t, 'sinal volta: realizado 60 + recibo')
    print('   sig', a.J("document.querySelector('main').innerText.split('\\n').slice(0,5).join(' / ')"), '| hdr', a.hdr())
    a.clk('Sem sinal'); a.clk('Com sinal', wait=.5); print('   toast2', a.toast())
    a.ok(a.cen(f"c.ordens['{OS}'].realizado") == 60 and a.cen(f"c.ordens['{OS}'].ap.length") == 1 and a.cen('(c.app.recibos||[]).length') == 1, 'sem duplicar')
    a.abrir('MB-03'); print('   MB-03 after:', a.main()[:900], '| hdr', a.hdr(), '| foot', a.foot())
    a.ok(not a.erros(), 'sem erros JS')
finally:
    a.fim()
