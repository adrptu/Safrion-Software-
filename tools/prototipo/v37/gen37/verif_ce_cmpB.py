    p=v.prim(); v.chk('recusada: primária Conferir demanda aberta', 'Conferir demanda aberta' in p, p)
    v.chk('recusada: sem botões de decisão', 'Registrar recusa' not in btns() and 'Registrar aprovação' not in p)
